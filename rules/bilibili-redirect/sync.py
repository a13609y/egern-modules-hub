#!/usr/bin/env python3
"""生成 BiliBili Redirect（Egern）：六组 Toggle 开关 + 上游 request.bundle.js 原样执行。

对应 96611db 真机超时的修法：
  · 不再覆盖 globalThis.$done，也不把上游的完成回调包进 Promise.race / setTimeout。
    上游 bundle 在 Egern 分支本来就走 `$done(a)`；沿用运行时原生 $done，请求才会像
    原版一样立刻结束。覆盖它 = 原生完成回调永不触发 → 脚本挂到引擎超时。
  · 不再重写 $request / $persistentStore（沿用 Egern 原生，与原版一致）。
  · 唯一新增：把 env_schema 的 Toggle 解析成 $argument 字符串后交给上游；解析全程
    try/catch，失败就退回运行时原生 $argument（fail open，不阻塞请求）。
  · 上游内容校验不过 → 不写文件、非零退出，保留上一版。

用法：python3 rules/bilibili-redirect/sync.py [--check]
"""
import json, os, re, sys, urllib.request
import yaml

TAG_API = 'https://api.github.com/repos/Biliverse/Redirect/releases/latest'
HERE = os.path.dirname(os.path.abspath(__file__))
RAW = 'https://raw.githubusercontent.com/a13609y/egern-modules-hub/main/rules/bilibili-redirect'

HOST_GROUPS = ['Host.OverseaVideo', 'Host.BStar', 'Host.PCDN', 'Host.MCDN']
ALL_GROUPS = HOST_GROUPS + ['Storage', 'LogLevel']
GROUP_OF = {'Host.OverseaVideo': '港澳台', 'Host.BStar': '国际版',
            'Host.PCDN': '大陆 PCDN', 'Host.MCDN': 'MCDN'}
SHORT = {
    'upos-sz-mirrorali.bilivideo.com': '阿里云 CDN',
    'upos-sz-mirrorcos.bilivideo.com': '腾讯云 CDN',
    'upos-sz-mirrorhw.bilivideo.com': '华为云 CDN',
    'upos-sz-mirrorhwo1.bilivideo.com': '华为云 o1',
    'upos-sz-mirror08c.bilivideo.com': '华为云 08c',
    'upos-sz-mirroraliov.bilivideo.com': '阿里云·海外',
    'upos-sz-mirrorcosov.bilivideo.com': '腾讯云·海外',
    'upos-sz-mirrorhwov.bilivideo.com': '华为云·海外',
    'proxy-tf-all-ws.bilivideo.com': 'MCDN 代理',
}


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'egern-modules-hub-sync'})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode('utf-8')


def candidates(desc):
    """上游 compat_arguments_desc → {参数: [(值, 说明)]}"""
    out, cur = {}, None
    for line in (desc or '').splitlines():
        m = re.match(r'^([A-Za-z.]+):\s', line)
        if m and m.group(1) in ALL_GROUPS:
            cur = m.group(1)
            out[cur] = []
            continue
        m = re.match(r'^\s+[├└]\s+([^:]+):\s*(.*)$', line)
        if cur and m:
            out[cur].append((m.group(1).strip(), m.group(2).strip()))
    return out


def toggle_key(group, value):
    return 'Bili_' + group.replace('Host.', '') + '__' + re.sub(r'[^a-z0-9]+', '_', value.lower()).strip('_')


def label(group, value):
    if value.startswith('cn-hk-eq-'):
        return f'{GROUP_OF.get(group, group)}：香港 {value[len("cn-hk-eq-"):][:5]}'
    if group == 'Storage':
        return f'配置来源：{value}'
    if group == 'LogLevel':
        return f'日志：{value}'
    return f'{GROUP_OF.get(group, group)}：{SHORT.get(value, value)}'


PRELUDE = '''/*! BiliBili Redirect (Egern) — toggle bridge, generated by a13609y/egern-modules-hub
 *  衍生自 Biliverse/Redirect 的 request.bundle.js（Apache-2.0，见同目录 LICENSE / NOTICE）。
 *  修改点：把 env_schema 的 Toggle 解析成 $argument，再原样执行上游 bundle。
 *  不覆盖 $done / $request / $persistentStore，不包 Promise、不设定时器：
 *  上游对 Egern 分支调用运行时原生 $done，请求因此和原版一样立即结束。
 */
export default async function (ctx) {
  // ── 开关表（sync.py 生成，勿手改）──
  const GROUPS = %(groups)s;
  const FALLBACK = %(fallback)s;
  try {
    const env = (ctx && ctx.env) || {};
    const isOn = function (v) {
      if (v === undefined || v === null) return false;
      const s = String(v).trim().toLowerCase();
      return s === 'true' || s === '1' || s === 'on' || s === 'yes';
    };
    const base = {};
    String(env['_compat.$argument'] || FALLBACK).replace(/^\\?/, '').split('&').forEach(function (seg) {
      const i = seg.indexOf('=');
      const k = i < 0 ? seg : seg.slice(0, i);
      const v = i < 0 ? '' : seg.slice(i + 1);
      if (!k || k.indexOf('{{{') >= 0 || v.indexOf('{{{') >= 0) return;
      try { base[decodeURIComponent(k)] = decodeURIComponent(v).replace(/"/g, ''); }
      catch (e) { base[k] = v.replace(/"/g, ''); }
    });
    GROUPS.forEach(function (g) {
      const on = g[1].filter(function (o) { return isOn(env[o[0]]); });
      if (on.length === 1) base[g[0]] = on[0][1];
    });
    const arg = Object.keys(base).map(function (k) {
      return encodeURIComponent(k) + '=' + encodeURIComponent(base[k]);
    }).join('&');
    try { globalThis.$argument = arg; } catch (e) {
      try { Object.defineProperty(globalThis, '$argument', { value: arg, writable: true, configurable: true }); } catch (e2) {}
    }
  } catch (e) { /* fail open：开关解析失败就用运行时原生 $argument */ }
  // ── 上游 bundle 原样执行（结束由上游调用原生 $done）──
%(upstream)s
}
'''


def build(up_yaml, up_js, tag):
    data = yaml.safe_load(up_yaml)
    for key in ('name', 'compat_arguments', 'url_rewrites', 'map_locals', 'scriptings', 'mitm'):
        if not data.get(key):
            raise SystemExit(f'上游缺少 {key}，保留上一版')
    if 'Host.OverseaVideo' not in up_js or 'request.bundle.js' not in up_js:
        raise SystemExit('上游 request.bundle.js 结构异常，保留上一版')
    cands = candidates(data.get('compat_arguments_desc'))
    for g in ALL_GROUPS:
        if not cands.get(g):
            raise SystemExit(f'上游 compat_arguments_desc 缺少分组 {g}，保留上一版')

    groups = [[g, [[toggle_key(g, v), v] for v, _ in cands[g]]] for g in HOST_GROUPS]
    fallback = '&'.join(f'{g}={cands[g][0][0]}' for g in ALL_GROUPS)
    bundle = PRELUDE % {
        'groups': '[' + ','.join(json.dumps(x, ensure_ascii=False) for x in groups) + ']',
        'fallback': json.dumps(fallback, ensure_ascii=False),
        'upstream': up_js.strip(),
    }

    out = {
        'name': '📺 BiliBili: 🔀 Redirect',
        'description': ('哔哩哔哩：重定向\n'
                        '六组参数每个上游候选值一个开关：每组只开一个生效，全关或多开按上游默认。\n'
                        f'上游版本：{tag}（由 a13609y/egern-modules-hub 每日生成，请勿手改）'),
        'compat_arguments': {g: data['compat_arguments'][g] for g in ALL_GROUPS},
        'compat_arguments_desc': '\n'.join(
            [f'{g}: 默认 {cands[g][0][0]}（可选值见开关列表，同组只开一个）' for g in ALL_GROUPS]
            + ['开关优先：某组恰有一个开关为开时用该值，否则用上面的默认值。']),
        'open_url': data.get('open_url'),
        'author': data.get('author'),
        'homepage': data.get('homepage'),
        'icon': data.get('icon'),
        'dns': data.get('dns') or {},
        'env_schema': {toggle_key(g, v): {'name': label(g, v),
                                          'description': '同组只开一个；全关或多开用上游默认。',
                                          'options': ['true', 'false']}
                       for g in ALL_GROUPS for v, _ in cands[g]},
        'scriptings': [{'http_request': {
            'name': s['http_request']['name'],
            'match': s['http_request']['match'],
            'script_url': f'{RAW}/bilibili-redirect.bundle.js',
            'env': {'_compat.$argument': '&'.join(
                f'{g}="{{{{{g}}}}}"' for g in ALL_GROUPS)},
        }} for s in data['scriptings']],
        'mitm': data['mitm'],
    }
    header = ('# 自动生成：python3 rules/bilibili-redirect/sync.py（上游 Biliverse/Redirect）\n'
              '# 请勿手改；修改生成逻辑请改 sync.py，每日 GitHub Actions 会重新生成覆盖本文件。\n'
              '# Apache-2.0：见同目录 LICENSE / NOTICE。\n')
    return header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=10000), bundle, out


def main():
    check = '--check' in sys.argv
    tag = json.loads(fetch(TAG_API))['tag_name']
    base = f'https://github.com/Biliverse/Redirect/releases/download/{tag}/'
    up_yaml, up_js = fetch(base + 'BiliBili.Redirect.yaml'), fetch(base + 'request.bundle.js')
    text, bundle, out = build(up_yaml, up_js, tag)
    # 自校验：能解析、字段齐、脚本 URL 指向本仓库、prelude 不碰 $done
    parsed = yaml.safe_load(text)
    assert parsed['env_schema'] and parsed['scriptings'] and parsed['mitm']
    assert all(RAW + '/bilibili-redirect.bundle.js' == s['http_request']['script_url'] for s in parsed['scriptings'])
    assert 'globalThis.$done =' not in bundle and 'setTimeout' not in bundle.split('// ── 上游 bundle 原样执行')[0]
    n = len(parsed['env_schema'])
    if check:
        print(json.dumps({'tag': tag, 'switches': n, 'scriptings': len(parsed['scriptings']),
                          'groups': {g: len(cands) for g, cands in
                                     ((g, [v for v, _ in c]) for g, c in
                                      ((g, candidates(parsed['compat_arguments_desc'])) for g in []))}},
                         ensure_ascii=False))
        return
    open(os.path.join(HERE, 'bilibili-redirect.yaml'), 'w', encoding='utf-8').write(text)
    open(os.path.join(HERE, 'bilibili-redirect.bundle.js'), 'w', encoding='utf-8').write(bundle)
    print(f'generated tag={tag} switches={n} scriptings={len(parsed["scriptings"])} bundle={len(bundle)}B')


if __name__ == '__main__':
    main()
